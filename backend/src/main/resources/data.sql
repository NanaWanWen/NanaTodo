-- 主表合计：由明细汇总回填，保证与明细口径一致
UPDATE po_order o
   SET total_qty    = IFNULL((SELECT SUM(i.qty)    FROM po_order_item i WHERE i.order_id = o.id AND i.deleted = 0), 0),
       total_amount = IFNULL((SELECT SUM(i.amount) FROM po_order_item i WHERE i.order_id = o.id AND i.deleted = 0), 0)
 WHERE o.id BETWEEN 9001 AND 9024;

